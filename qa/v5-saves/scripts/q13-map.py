# Map extracted Saves-lane rows (q13-rows.json) to gate coverage buckets; writes q13-saves-lane-rows.md. Keyword heuristic, reviewed by hand at the RC.
import json, re, collections
R = json.load(open('q13-rows.json'))
B = [  # (bucket, regex, mapping, status)
 ('ROLE', r'^$', '§0 role summary (not a case)', 'n/a'),
 ('PAUSE', r'.', 'N/A if Pause is cut (manifest rule 1)', 'conditional'),
 ('SAVE', r'save|migrat|downgrade|old-save|old save|readyAt|reload|v6|SAVE_VERSION|field', 'saves-browser S-UP/S-RT/S-COLD + noLoss N3 over M5_KEYS (generic part COVERED); feature-specific values need an RC binding', 'partial'),
 ('OFFLINE', r'offline|clock|frame gap|hidden|focusClock|welcome|gap|wall', 'saves-browser S-OFF/S-CLK + TS2 hidden stub (generic COVERED); feature timers/clamps NOT covered', 'partial'),
 ('TELEM', r'telemetry|event|session_end|T-AC|ring|export', 'telemetry-check schema/allowlist (COVERED once events are in the schema); per-feature firing rules NOT covered', 'partial'),
 ('GOLDEN', r'byte-ident|golden|flag-off|flag off|m4\.enabled|two builds', 'flag-off goldens / two-build byte identity: NOT in driver; re-run CI goldens + noreg on the RC (add step)', 'not covered'),
 ('TRACE', r'AC7|trace|seeds|harness|CI|sim|G5|X1|bot', 'trace/sim harness (needs bot-m5, manifest row 2, and X1 job): NOT covered by the Saves driver', 'not covered'),
 ('UNIT', r'.', 'pure-selector/maths unit test against M5 source: NOT covered; needs a vitest suite written once the PR exists', 'not covered'),
]
def bucket(r):
    if r['id'].startswith('Saves QA'): return B[0]
    if 'pause' in r['plan']: return B[1]
    t = r['id'] + ' ' + r['need'] + ' ' + r['type']
    for b in B[2:]:
        if re.search(b[1], t, re.I): return b
for r in R: b = bucket(r); r['bucket'], r['map'], r['status'] = b[0], b[2], b[3]
json.dump(R, open('q13-rows.json', 'w'), indent=1, ensure_ascii=False)
c = collections.Counter(r['bucket'] for r in R); cp = collections.Counter((r['plan'], r['bucket']) for r in R)
L = ['# Q13: Saves-lane rows of every qa/m5 plan (V5-S), mapped to the gate', '',
     'Generated by `scripts/q13-extract.py` + `scripts/q13-map.py` (2026-10-29 CET) from qa/m5/test-plan-*.md (read as data). The bucket is a keyword heuristic; each row gets a hand check when its PR lands.', '',
     '| bucket | rows | mapping |', '|---|---|---|'] + [f"| {b[0]} | {c.get(b[0],0)} | {b[2]} |" for b in B] + ['', '| plan (sha1) | ' + ' | '.join(b[0] for b in B) + ' |', '|---|' + '---|' * len(B)]
for p in sorted({r['plan'] for r in R}):
    L.append(f"| {p} ({next(r['sha1'] for r in R if r['plan']==p)}) | " + ' | '.join(str(cp.get((p, b[0]), 0)) for b in B) + ' |')
L += ['', '## All rows', '', '| plan | line | row id | type | lane | bucket | what it needs (truncated) |', '|---|---|---|---|---|---|---|']
for r in R: L.append(f"| {r['plan'][10:-3]} | L{r['line']} | {r['id']} | {r['type']} | {r['lane']} | {r['bucket']} | {r['need'][:220].replace('|','/')} |")
open('q13-saves-lane-rows.md', 'w').write('\n'.join(L) + '\n'); print(c, len(R))
