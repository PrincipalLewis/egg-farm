import json, glob, hashlib, subprocess, sys, os
SHA = sys.argv[1] if len(sys.argv) > 1 else 'c877f69a407ec844a4d10612030584be42e34bdf'
S7 = SHA[:7]
os.chdir(f'/workspace/egg-farm-studio/qa/m41/m41-9-{S7}')
h = lambda p: hashlib.sha256(open(p, 'rb').read()).hexdigest()
ls = subprocess.run(['git', '-C', '/workspace/egg-farm-studio/game', 'ls-remote', 'origin'], capture_output=True, text=True).stdout
refs = [l.split('\t')[1] for l in ls.splitlines() if l.startswith(SHA)]
summ = open('gates/summary.txt').read() if os.path.exists('gates/summary.txt') else ''
p65_runs = []
for f in sorted(glob.glob('browser/entries-*.jsonl')):
  L = [json.loads(x) for x in open(f)]
  d = [x for x in L if x.get('done')]
  p65_runs.append({'file': f, 'complete': bool(d), 'after_fails': d[-1]['fails'] if d else None, 'before_defects': sorted(set(d[-1]['beforeDefects'])) if d else None})
tap_runs = []
for f in sorted(glob.glob('browser/tap-*.jsonl')):
  L = [json.loads(x) for x in open(f)]
  d = [x for x in L if x.get('done')]
  taps = [x for x in L if x.get('recordType') == 'tap' and x.get('lab') == 'after']
  states = [x for x in L if x.get('recordType') == 'state' and x.get('lab') == 'after']
  tap_runs.append({
    'file': f,
    'complete': bool(d),
    'after_states': len(states),
    'after_overlaps': sum(1 for x in states if x.get('anyOverlap')),
    'after_taps_mouse': sum(1 for x in taps if x['input'] == 'mouse'),
    'after_taps_touch': sum(1 for x in taps if x['input'] == 'touch'),
    'after_buys': sum(1 for x in taps if x['bought']),
    'after_dismiss_only': sum(1 for x in taps if 'DISMISS-ONLY' in x['outcome']),
    'after_nothing': sum(1 for x in taps if x['outcome'] == 'NOTHING'),
    'pageerrors': d[-1]['pageerrors'] if d else None
  })
shots = [{'path': p, 'sha256': h(p)} for p in sorted(glob.glob('shots/*/*.png'))]
m = {
  'pr': 65,
  'sha': SHA,
  'branch': 'fix/m41-9-ux-minors',
  'pushed': bool(refs),
  'pushed_refs': refs,
  'merged': False,
  'base': 'dd223f510e9acabf9b1915b56e39da8b88dcac63',
  'ff_from': '77790883c2d6b0e6bd0db8e786d04bb87579c68a',
  'build_id': f'm3-rc1-pre+{S7}',
  'before_build_id': 'm3-rc1-pre+dd223f5',
  'build_id_runtime_verified': 'meta[name=build-id] read in-page in every context (AFTER and BEFORE) before any measurement; probe aborts on mismatch or +dirty',
  'dist': [l for l in summ.splitlines() if l.startswith('dist')],
  'art_spec': {'path': 'art-ux/m4.1-ui-minors.md', 'sha256': h('/workspace/egg-farm-studio/art-ux/m4.1-ui-minors.md')},
  'checkout': f'/tmp/qa-m41-9-{S7} clean (porcelain empty before/after gates)',
  'before_tree': '/tmp/qa-m41-9-base-dd223f5 (clean dd223f5, own dist-qa)',
  'not_reused': '/workspace/wt-ui-shots/ was not reused as QA screenshot evidence; all shots under shots/ are generated by QA probes browser/p65-tap.mjs and browser/p65.mjs',
  'p65_runs': p65_runs,
  'tap_runs': tap_runs,
  'shot_count': len(shots),
  'shots': shots
}
json.dump(m, open('manifest.json', 'w'), indent=1)
json.dump(m, open('shots/manifest.json', 'w'), indent=1)
print(len(shots), 'shots | p65:', [(r['file'], r['complete'], len(r['after_fails'] or [])) for r in p65_runs], '| tap:', [(r['file'], r['complete'], r['after_buys'], r['after_dismiss_only'], r['after_nothing']) for r in tap_runs])
